# 派生上限：一个高产词最多再带出几个兄弟词（防止词表爆炸、把采集时间拖长）。
SIBLING_CAP = 6

# 单次展开后词表总量上限（扩词必须有界：无界展开一夜把请求量放大几十倍）
MAX_KEYWORDS = 200


def _family_of(kw):
    """返回该关键词命中的同族词根（结尾匹配优先于全等，取最长词根）。"""
    best = ""
    for root in SIBLING_FAMILIES:
        if (kw == root or kw.endswith(root)) and len(root) > len(best):
            best = root
    return best


def derive_siblings(kw, pool=None):
    """把一个高产词派生成同族近义词：已在 pool（当前词表）里的一律不再返回，
    词根自身也不返回（它已在表里）。pool 传 None 时只去重本函数自己的输出。"""
    root = _family_of(str(kw or "").strip())
    if not root:
        return []
    seen = set(pool or [])
    out = []
    for w in SIBLING_FAMILIES[root]:
        if w == kw or w in seen:
            continue
        seen.add(w)
        out.append(w)
        if len(out) >= SIBLING_CAP:
            break
    return out


def boost_high_yield(keywords, kw_yield, min_yield=20):
    """产出反馈闭环：把「已经证明高产」的关键词横向派生同族近义词补进词表。

    keywords —— 当前词表（顺序保留）
    kw_yield  —— 关键词 → 本轮净新增条数（各站合并后的账目）
    min_yield —— 判定"高产"的门槛（条），低于它的词不派生（多半本身就窄）
    返回 {"keywords": 新词表, "added": [(原词, 净新增, [派生词...]), ...]}
    """
    pool = [str(k).strip() for k in (keywords or []) if str(k).strip()]
    result = list(pool)
    seen = set(pool)
    added = []
    for kw in pool:
        n = int((kw_yield or {}).get(kw, 0) or 0)
        if n < min_yield:
            continue
        sib = derive_siblings(kw, seen)
        if not sib:
            continue
        for w in sib:
            seen.add(w)
            result.append(w)
        added.append((kw, n, sib))
    return {"keywords": result, "added": added}
