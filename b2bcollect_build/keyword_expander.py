# 输入按这些分隔符切成「片段」（类别名一般一行一个；也兼容顿号/斜杠并列）
_SEG_RE = re.compile(r"[\r\n,;，；、/|\t]+")


def _segment(text):
    """把原始文本切成待判定片段：去序号前缀、去首尾空白、丢弃过短碎片。"""
    if not text:
        return []
    out = []
    for seg in _SEG_RE.split(text):
        k = re.sub(r"\s+", " ", seg).strip()
        k = re.sub(r"^\d+[.、]\s*", "", k)          # 去「1. 」「2、」序号
        k = re.sub(r"[（(【\[][^）)】\]]*[）)】\]]", "", k).strip(" 　・-")  # 去括注
        if len(k) < 2 or not re.search(r"[\u4e00-\u9fa5A-Za-z0-9]", k):
            continue
        out.append(k)
    return out


def _fields(entry):
    """条目统一拆成（类别名, 特征短语, 产品词, 关联类别名）。
    第 4 段是可选的：老条目只有 3 段，新增的同产业链类别靠它互相关联。"""
    return entry[0], entry[1], entry[2], list(entry[3]) if len(entry) > 3 else []


_PRODUCTS_BY_NAME = {e[0]: e[2] for e in KNOWLEDGE_BASE}


def _match_entry(seg):
    """返回该片段命中的知识库条目（最长特征短语优先）；未命中返回 None。"""
    best, best_len = None, 0
    for entry in KNOWLEDGE_BASE:
        for ph in entry[1]:
            if ph in seg and len(ph) > best_len:
                best, best_len = entry, len(ph)
    return best


def _related_products(entry, depth=2):
    """沿「关联类别」再收一轮产品词（带 visited 防互引成环）。
    只补产品词、不再往下匹配特征短语，避免一个宽泛词把整库都拉进来。"""
    name, _phrases, products, related = _fields(entry)
    out = list(products)
    seen = {name}
    frontier = related
    for _ in range(depth):
        nxt = []
        for rn in frontier:
            if rn in seen:
                continue
            seen.add(rn)
            more = _PRODUCTS_BY_NAME.get(rn)
            if more:
                out.extend(more)
            for e in KNOWLEDGE_BASE:
                if e[0] == rn:
                    nxt.extend(_fields(e)[3])
        frontier = nxt
        if not frontier:
            break
    return out


def _is_drop(seg):
    return any(m in seg for m in DROP_MARKS)


def expand_keywords(text):
    """智能解析主入口。

    返回 dict：
      keywords   —— 展开+去重后的最终产品词列表（保持出现顺序）
      expanded   —— 命中知识库、被展开的输入片段 [(原片段, 类别名, 产品数), ...]
      kept       —— 未命中知识库、也不是服务词，原样保留的片段（多半本就是产品词）
      dropped    —— 被忽略的纯服务/流程词片段
    """
    result, seen = [], set()
    expanded, kept, dropped = [], [], []

    for seg in _segment(text):
        hit = _match_entry(seg)
        if hit:
            name = hit[0]
            products = _related_products(hit)
            added = 0
            for p in products:
                if p not in seen:
                    seen.add(p)
                    result.append(p)
                    added += 1
            expanded.append((seg, name, added))
        elif _is_drop(seg):
            dropped.append(seg)
        else:
            if seg not in seen:
                seen.add(seg)
                result.append(seg)
            kept.append(seg)

    # 词表总量上限：扩词必须有界。用户粘一整份行业目录进来时，无界展开会造出
    # 上千个词，一夜之间把请求量放大几十倍（防采风险 + 绝大部分词根本轮不到跑）。
    truncated = len(result) > MAX_KEYWORDS
    if truncated:
        result = result[:MAX_KEYWORDS]
    return {"keywords": result, "expanded": expanded,
            "kept": kept, "dropped": dropped, "truncated": truncated}


