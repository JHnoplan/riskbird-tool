# 输入按这些分隔符切成「片段」（类别名一般一行一个；也兼容顿号/斜杠并列）
_SEG_RE = re.compile(r"[\r\n,;，；、/|\t]+")


def _segment(text):
    """把原始文本切成待判定片段：去序号前缀、去首尾空白、丢弃过短碎片。"""
    if not text:
        return []
    out = []
    for seg in _SEG_RE.split(text):
        k = re.sub(r"\s+", " ", seg).strip()
        k = re.sub(r"^\d+[.、]\s*", "", k)          # 去「1. 」「2、」序号
        k = re.sub(r"[（(【\[][^）)】\]]*[）)】\]]", "", k).strip(" 　・-")  # 去括注
        if len(k) < 2 or not re.search(r"[\u4e00-\u9fa5A-Za-z0-9]", k):
            continue
        out.append(k)
    return out


def _match_entry(seg):
    """返回该片段命中的知识库条目（最长特征短语优先）；未命中返回 None。"""
    best, best_len = None, 0
    for name, phrases, products in KNOWLEDGE_BASE:
        for ph in phrases:
            if ph in seg and len(ph) > best_len:
                best, best_len = (name, products), len(ph)
    return best


def _is_drop(seg):
    return any(m in seg for m in DROP_MARKS)


def expand_keywords(text):
    """智能解析主入口。

    返回 dict：
      keywords   —— 展开+去重后的最终产品词列表（保持出现顺序）
      expanded   —— 命中知识库、被展开的输入片段 [(原片段, 类别名, 产品数), ...]
      kept       —— 未命中知识库、也不是服务词，原样保留的片段（多半本就是产品词）
      dropped    —— 被忽略的纯服务/流程词片段
    """
    result, seen = [], set()
    expanded, kept, dropped = [], [], []

    for seg in _segment(text):
        hit = _match_entry(seg)
        if hit:
            name, products = hit
            added = 0
            for p in products:
                if p not in seen:
                    seen.add(p)
                    result.append(p)
                    added += 1
            expanded.append((seg, name, added))
        elif _is_drop(seg):
            dropped.append(seg)
        else:
            if seg not in seen:
                seen.add(seg)
                result.append(seg)
            kept.append(seg)

    return {"keywords": result, "expanded": expanded,
            "kept": kept, "dropped": dropped}
